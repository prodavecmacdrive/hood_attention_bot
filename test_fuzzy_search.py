# coding: utf-8
from database import Database

db = Database()

print("=== Тест нечеткого поиска районов ===\n")

test_queries = [
    # Точные совпадения
    ('Салтовка', 'Точное совпадение'),
    ('хтз', 'Точное совпадение (аббревиатура)'),
    ('602', 'Точное совпадение (цифры)'),
    
    # Опечатки
    ('Солтовка', 'Опечатка: "о" вместо "а"'),
    ('Салтвка', 'Пропущена буква "о"'),
    ('Хьтз', 'Опечатка в аббревиатуре'),
    
    # Частичные совпадения
    ('салт', 'Частичное совпадение'),
    ('павлов', 'Частичное совпадение'),
    ('жук', 'Частичное совпадение'),
    
    # Разный регистр
    ('САЛТОВКА', 'Верхний регистр'),
    ('СаЛтОвКа', 'Смешанный регистр'),
    
    # Сложные случаи
    ('павлово поле', 'Несколько слов'),
    ('холодная', 'Часть из двух слов'),
    
    # Совсем неправильные
    ('абракадабра', 'Несуществующий район'),
    ('москва', 'Неправильный город'),
]

for query, description in test_queries:
    print(f"\n{'='*60}")
    print(f"Запрос: '{query}'")
    print(f"Описание: {description}")
    print('-' * 60)
    
    results = db.search_districts(query, limit=5, threshold=60)
    
    if results:
        print(f"Найдено: {len(results)}")
        for i, (dist_id, dist_name, score) in enumerate(results, 1):
            print(f"  {i}. {dist_name} ({score}%)")
    else:
        print("❌ Ничего не найдено")

print("\n" + "="*60)
print("Тест завершен!")
